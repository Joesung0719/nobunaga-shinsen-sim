// 加經驗，回傳升了幾級；每升一級得 1 點自由點數（Lv50 共 49 點）
export function addExp(h,n){
  let up=0;h.exp+=Math.round(n);
  while(h.lv<MAXLV&&h.exp>=expNeed(h.lv)){h.exp-=expNeed(h.lv);h.lv++;h.free++;up++}
  if(h.lv>=MAXLV)h.exp=0;
  return up;
}
